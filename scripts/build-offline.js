'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),pub=path.join(root,'public'),KM=require('../public/engine');
const svg=fs.readFileSync(path.join(pub,'lake.svg'),'utf8');
const img='data:image/svg+xml;base64,'+Buffer.from(svg).toString('base64');
const css=fs.readFileSync(path.join(pub,'style.css'),'utf8').replaceAll("url('lake.svg')",`url('${img}')`);
const js=fs.readFileSync(path.join(pub,'app.js'),'utf8').replaceAll('src="lake.svg"',`src="${img}"`);
const engine=fs.readFileSync(path.join(pub,'engine.js'),'utf8');
const graphics=fs.readFileSync(path.join(pub,'lab2d.js'),'utf8')+fs.readFileSync(path.join(pub,'lab3d.bundle.js'),'utf8').replace(/<\/script/gi,'<\\/script');
const lab=fs.readFileSync(path.join(pub,'lab.js'),'utf8');
const html=`<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>湖畔实验室 · 离线练习</title><style>${css}</style></head><body><div id="app"></div><div id="toast" role="status" aria-live="polite"></div><script>window.OFFLINE=true;</script><script>${engine}</script><script>${graphics}</script><script>${lab}</script><script>${js}</script></body></html>`;
fs.writeFileSync(path.join(pub,'offline.html'),html);
const rows=[['点位（教学模拟）',...KM.FEATURES.map(f=>`${f.name} (${f.unit})`),'来源'],...KM.DATA.map(p=>[p.id,...p.values,'固定规则生成，非实测，无类别标签'])];
fs.writeFileSync(path.join(pub,'data-40.csv'),'\uFEFF'+rows.map(r=>r.join(',')).join('\r\n'));
const curves={};for(const dims of [2,3,5])curves[dims]=KM.elbow(dims,'zscore');
const runs=[];for(let seed=1;seed<=40;seed++)runs.push(KM.experiment({dims:3,k:3,mode:'zscore',seed}));
fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
fs.writeFileSync(path.join(root,'artifacts','math-reference.json'),JSON.stringify({hand:KM.handExpected(),curves,initializations:runs.map(x=>({dims:x.dims,seed:x.seed,sse:x.sse,labels:x.labels}))},null,2));
console.log('离线单文件、40点数据和计算参考已生成。');
