const assert=require('node:assert/strict'),path=require('node:path');
module.exports=async function scalingFlow(page,out){
  await page.locator('#scaleActivity').waitFor();
  assert.equal(await page.locator('.scale-result').count(),0,'prediction precedes the revealed distances');
  await page.locator('[data-center="0,0"]').fill('0.123');
  await page.locator('[data-action="scale-predict"][data-value="same"]').click();
  assert((await page.locator('#scaleNearest').innerText()).includes('最近：乙'));
  assert(await page.locator('#scaleMethodToggle').isDisabled());
  await page.locator('#scaleUnitToggle').click();
  assert((await page.locator('#scaleNearest').innerText()).includes('最近：丙'));
  assert((await page.locator('#scaleInsight').innerText()).includes('你的预测：不会变'));
  assert.equal(await page.locator('#scaleActivity tbody tr').first().locator('td').nth(1).innerText(),'200');
  if(out)await page.locator('#scaleIntro').screenshot({path:path.join(out,'02d-scale-unit-change.png')});
  await page.locator('#scaleMethodToggle').click();
  const distances=await page.locator('.scale-equation').allTextContents();
  assert((await page.locator('#scaleActivity .formula').innerText()).includes('200 μg/L'));
  await page.locator('#scaleUnitToggle').click();
  assert.deepEqual(await page.locator('.scale-equation').allTextContents(),distances);
  assert((await page.locator('#scaleNearest').innerText()).includes('最近：丙'));
  assert((await page.locator('#scaleInsight').innerText()).includes('两种单位下的缩放结果一致'));
  assert.equal(await page.locator('[data-center="0,0"]').inputValue(),'0.123','activity preserves hand-work input');
  await page.reload();await page.locator('#scaleActivity').waitFor();
  assert.deepEqual(await page.locator('.scale-equation').allTextContents(),distances);
  assert.equal(await page.locator('[data-center="0,0"]').inputValue(),'0.123');
  if(out)await page.locator('#scaleIntro').screenshot({path:path.join(out,'02e-scale-rescaled.png')});
  const viewport=page.viewportSize();await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  if(out)await page.locator('#scaleIntro').screenshot({path:path.join(out,'02f-scale-mobile.png')});
  await page.setViewportSize(viewport);
  await page.locator('[data-action="scale-done"]').click();
  assert.equal(await page.locator('#scaleActivity').getAttribute('open'),null);
  await page.reload();assert.equal(await page.locator('#scaleActivity').getAttribute('open'),null);
  assert(await page.getByRole('heading',{name:'为什么要先统一尺度？',exact:true}).isVisible());
  assert((await page.locator('#scaleReason').innerText()).includes('K-means 根据距离分组'));
};
